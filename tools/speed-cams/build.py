#!/usr/bin/env python3
"""The public speed camera list -> apps/cluster_redline/speed-cams-data.js (Cluster Redline's speed camera alerts).

Kept: cameras with a speed limit that check speed: 단속구분 1 / 01 (speed), 1+2 / 01+02 (speed and signal), 3 / 03, 99
and 4 / 04 (multi-purpose) with a limit; signal-only ones (2 / 02) only inside a children's or elderly zone (shown as that
zone). Without a limit (0, mostly parking enforcement) they are left out.
Each camera: 12 bytes, little endian: lat int32 and lon int32 (millionths of a degree), limit u8, flags u8 (1 children's
zone, 2 elderly zone, 4 section start, 8 section end, 16 signal only), section length u16 (metres / 10).
"""
import base64, collections, json, os, struct, sys
SPEED = {'1', '01', '1+2', '01+02', '3', '03', '99', '4', '04'}
SIGNAL = {'2', '02'}
CHILD, ELDER = {'2', '02'}, {'1', '01'}
def num(s):
    try:
        return float(s)
    except (TypeError, ValueError):
        return None
def main():
    rows = json.load(open(sys.argv[1]))
    out, kinds, dates = [], collections.Counter(), collections.Counter()
    seen = set()
    for r in rows:
        lat, lon, limit = num(r.get('LATITUDE')), num(r.get('LONGITUDE')), num(r.get('LMTT_VE'))
        if lat is None or lon is None or not (33 <= lat <= 39 and 124 <= lon <= 132) or not limit or limit <= 0 or limit > 130:
            continue
        se, zone = (r.get('REGLT_SE') or '').strip(), (r.get('PRTCAREA_TYPE') or '').strip()
        flags = (1 if zone in CHILD else 0) | (2 if zone in ELDER else 0)
        if se in SIGNAL:
            if not flags:
                continue
            flags |= 16
        elif se not in SPEED:
            continue
        sec = (r.get('REGLT_SCTN_LC_SE') or '').strip()
        flags |= 4 if sec in ('1', '01') else 8 if sec in ('2', '02') else 0
        length = num(r.get('OVRSPD_REGLT_SCTN_LT')) or 0
        key = (round(lat * 1e5), round(lon * 1e5), int(limit), flags & 12)
        if key in seen:
            continue
        seen.add(key)
        out.append((round(lat * 1e6), round(lon * 1e6), int(limit), flags, min(65535, round(length * 100)) if flags & 12 else 0))
        kinds['section' if flags & 12 else 'child' if flags & 1 else 'elder' if flags & 2 else 'speed'] += 1
        dates[(r.get('REFERENCE_DATE') or '')[:10]] += 1
    out.sort()
    blob = b''.join(struct.pack('<iiBBH', *c) for c in out)
    newest = max(d for d in dates if d)
    here = os.path.dirname(os.path.abspath(__file__))
    target = os.path.join(here, '..', '..', 'apps', 'cluster_redline', 'speed-cams-data.js')
    with open(target, 'w') as f:
        f.write("'use strict';\n// Generated by tools/speed-cams/build.py from 공공데이터포털 전국무인교통단속카메라표준데이터 (publicDataPk 15028200,\n"
                "// 공공누리 제1유형). Do not edit; rebuild with tools/speed-cams/fetch.py and build.py.\n")
        f.write('module.exports = %s;\n' % json.dumps({'date': newest, 'count': len(out), 'record': 12, 'b64': base64.b64encode(blob).decode()}))
    print(len(out), 'cameras', dict(kinds), 'newest', newest, os.path.getsize(target), 'bytes')
if __name__ == '__main__':
    main()
