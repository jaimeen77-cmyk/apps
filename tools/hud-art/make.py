#!/usr/bin/env python3
"""Cluster Redline HUD art (1.3.80; guidance icons 1.3.81): the car in the lane-lines picture and the headway badge's icons, cut from the
user's own reference picture (transparent PNGs here), embedded in apps/cluster_redline/hud-art.js as zlib'd RGBA."""
import base64, os, zlib
from PIL import Image
HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, '..', '..', 'apps', 'cluster_redline', 'hud-art.js')
parts = []
from PIL import ImageFilter
def lane_on(im, lit_rgb=(0.35, 1.05, 1.6), glow_rgb=(40, 150, 255)):
    # a lane's selected arrow (1.3.81): the grey arrow lit in the sheet's blue, with a soft glow round it
    r, g, b, a = im.split(); L = im.convert('L')
    a = a.point(lambda v: min(255, v * 2))   # lit: solid, not the grey's half-seen
    lit = Image.merge('RGBA', (L.point(lambda v: int(min(255, v * lit_rgb[0] + (30 if lit_rgb[0] > 1 else 0)))), L.point(lambda v: int(min(255, v * lit_rgb[1] + 30))), L.point(lambda v: int(min(255, v * lit_rgb[2] + (30 if lit_rgb[2] > 1 else 0)))), a))
    pad = 8; big = Image.new('RGBA', (im.size[0] + 2 * pad, im.size[1] + 2 * pad), (0, 0, 0, 0))
    glow = Image.new('RGBA', big.size, glow_rgb + (0,)); ga = Image.new('L', big.size, 0); ga.paste(a, (pad, pad))
    glow.putalpha(ga.filter(ImageFilter.GaussianBlur(4)).point(lambda v: int(v * 0.7)))
    big.alpha_composite(glow); big.alpha_composite(lit, (pad, pad)); return big
def trunk(im):
    # where the arrow's trunk meets the lane's bottom: the alpha's centre across the lowest rows (0..1 of the width)
    a = im.split()[3]; W, H = im.size; tot = sx = 0
    for y in range(int(H * 0.85), H):
        for x in range(W):
            v = a.getpixel((x, y))
            if v > 128: tot += v; sx += v * x
    return round(sx / tot / W, 3) if tot else 0.5
# (1.3.86) one data file a set, read only when a picture of that set is drawn: the cars, the blue icons (nav/), the
# neon icons (neon/, the user's second sheet)
SETS = {'cars': [('car', 'car.png'), ('ok', 'icon-ok.png'), ('amber', 'icon-amber.png'), ('red', 'icon-red.png')], 'nav': [], 'neon': []}
SKIP = ('lg-slight-right-on.png', 'lg-left-b.png', 'lg-straight-b.png')
LIT = {'nav': ((0.35, 1.05, 1.6), (40, 150, 255)), 'neon': ((0.85, 1.2, 0.2), (170, 255, 40))}
extras = {'cars': {}, 'nav': {}, 'neon': {}}
for st in ('nav', 'neon'):
    D = os.path.join(HERE, st)
    for f in sorted(os.listdir(D)):
        if f.endswith('.png') and f not in SKIP: SETS[st].append((st + '/' + f[:-4], os.path.join(st, f)))
    for n in ['lg-uturn-left', 'lg-slight-left', 'lg-left', 'lg-straight', 'lg-slight-right']:
        extras[st][st + '/' + n + '-on'] = lane_on(Image.open(os.path.join(D, n + '.png')).convert('RGBA'), *LIT[st])
DATA = {}
for st in SETS:
    parts = []
    for key, name in SETS[st] + list(extras[st].items()):
        im = name if isinstance(name, Image.Image) else Image.open(os.path.join(HERE, name)).convert('RGBA')
        b64 = base64.b64encode(zlib.compress(im.tobytes(), 9)).decode()
        parts.append("  '%s': { w: %d, h: %d, z: '%s' }" % (key, im.size[0], im.size[1], b64))
    DATA[st] = parts
head = """'use strict';
// Generated by tools/hud-art/make.py: the HUD's pictures as RGBA (straight alpha), zlib'd, from the user's reference.
// paint(cv, name, x, y, w, h): drawn onto a ScaledCanvas at x, y (its units), w x h, bilinear, alpha-blended.
"""
body = """const cache = {};
function hsv(r, g, b) { const mx = Math.max(r, g, b), mn = Math.min(r, g, b), d = mx - mn; let h = 0;
    if (d) h = mx === r ? ((g - b) / d) % 6 : mx === g ? (b - r) / d + 2 : (r - g) / d + 4; return [(h * 60 + 360) % 360, mx ? d / mx : 0, mx / 255]; }
function rgb(h, s, v) { const c = v * s, x = c * (1 - Math.abs((h / 60) % 2 - 1)), m = v - c, k = Math.floor(h / 60) % 6;
    const t = [[c, x, 0], [x, c, 0], [0, c, x], [0, x, c], [x, 0, c], [c, 0, x]][k]; return t.map((q) => Math.round((q + m) * 255)); }
const hex = (c) => { if (Array.isArray(c)) return c; const m = /^#([0-9a-f]{6})$/i.exec(c || ''); if (!m) return null; const n = parseInt(m[1], 16); return [n >> 16 & 255, n >> 8 & 255, n & 255]; };
// tint: the picture's colour (its blue) turned to this one, its greys kept; flip: mirrored left to right
const SET_FILES = { nav: './hud-art-nav', neon: './hud-art-neon' }, loaded = {};
// a picture's data: its set's file read the first time a picture of that set is wanted
function art(name) {
    const st = SET_FILES[String(name).split('/')[0]] ? String(name).split('/')[0] : 'cars';
    if (!loaded[st]) { try { loaded[st] = require(SET_FILES[st] || './hud-art-cars'); } catch (e) { loaded[st] = {}; } }
    return loaded[st][name] || null;
}
function image(name, tint, flip) {
    const key = name + '|' + (tint || '') + '|' + (flip ? 1 : 0);
    if (cache[key]) return cache[key];
    const a = art(name); if (!a) return null;
    let d = require('zlib').inflateSync(Buffer.from(a.z, 'base64'));
    const t = hex(tint);
    if (t || flip) {
        const out = Buffer.alloc(d.length), T = t ? hsv(t[0], t[1], t[2]) : null;
        for (let y = 0; y < a.h; y++) for (let x = 0; x < a.w; x++) {
            const si = (y * a.w + x) * 4, di = (y * a.w + (flip ? a.w - 1 - x : x)) * 4;
            let r = d[si], g = d[si + 1], b = d[si + 2];
            if (T) { const p = hsv(r, g, b); if (p[1] > 0.18) { const q = rgb(T[0], Math.min(1, p[1] * (T[1] < 0.15 ? 0.08 : T[1] / 0.85)), Math.min(1, p[2] * (T[1] < 0.15 ? 1.05 : 1))); r = q[0]; g = q[1]; b = q[2]; } }
            out[di] = r; out[di + 1] = g; out[di + 2] = b; out[di + 3] = d[si + 3];
        }
        d = out;
    }
    return (cache[key] = { w: a.w, h: a.h, d });
}
// o: {tint, flip, alpha (0..1)}; false when cv has no pixels to paint (a drawing view without one)
function paint(cv, name, x, y, w, h, o) {
    o = o || {};
    const im = image(name, o.tint, o.flip), c = cv && (cv.canvas || cv), k = (cv && cv.k) || 1;
    if (!im || !c || !c.d || !c.w) return false;
    const d = c.d, s = im.d, alpha = o.alpha === undefined ? 1 : o.alpha;
    const X0 = Math.round(x * k), Y0 = Math.round(y * k), Wd = Math.max(1, Math.round(w * k)), Hd = Math.max(1, Math.round(h * k));
    for (let py = Math.max(0, Y0); py < Math.min(c.h, Y0 + Hd); py++) {
        const fy = Math.max(0, Math.min(im.h - 1.001, (py - Y0 + 0.5) * im.h / Hd - 0.5)), y0 = fy | 0, ty = fy - y0;
        for (let px = Math.max(0, X0); px < Math.min(c.w, X0 + Wd); px++) {
            const fx = Math.max(0, Math.min(im.w - 1.001, (px - X0 + 0.5) * im.w / Wd - 0.5)), x0 = fx | 0, tx = fx - x0;
            const i00 = (y0 * im.w + x0) * 4, i10 = i00 + 4, i01 = i00 + im.w * 4, i11 = i01 + 4;
            const w00 = (1 - tx) * (1 - ty), w10 = tx * (1 - ty), w01 = (1 - tx) * ty, w11 = tx * ty;
            const a00 = s[i00 + 3] * w00, a10 = s[i10 + 3] * w10, a01 = s[i01 + 3] * w01, a11 = s[i11 + 3] * w11, sa = (a00 + a10 + a01 + a11) / 255 * alpha;
            if (sa <= 0.004) continue;
            const di = (py * c.w + px) * 4, da = d[di + 3] / 255, oa = sa + da * (1 - sa);
            for (let ch = 0; ch < 3; ch++) {
                const sc = (s[i00 + ch] * a00 + s[i10 + ch] * a10 + s[i01 + ch] * a01 + s[i11 + ch] * a11) / (sa / alpha * 255);
                d[di + ch] = Math.round((sc * sa + d[di + ch] * da * (1 - sa)) / oa);
            }
            d[di + 3] = Math.round(oa * 255);
        }
    }
    return true;
}
const size = (name) => { const a = art(name); return a ? { w: a.w, h: a.h } : null; };
const loadedSets = () => Object.keys(loaded);
module.exports = { paint, image, size, loadedSets };
"""
with open(OUT, 'w') as f:
    f.write(head + body)
for st in DATA:
    path = os.path.join(os.path.dirname(OUT), 'hud-art-%s.js' % st)
    with open(path, 'w') as f:
        f.write("'use strict';\n// Generated by tools/hud-art/make.py: the %s pictures (RGBA, straight alpha, zlib'd); read through hud-art.js.\nmodule.exports = {\n%s\n};\n" % (st, ",\n".join(DATA[st])))
    print('wrote', path, os.path.getsize(path))
print('wrote', OUT, os.path.getsize(OUT))
